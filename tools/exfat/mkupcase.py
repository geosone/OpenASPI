#!/usr/bin/env python3
"""Generates common/exfat/upcase.c: the recommended up-case table of the
exFAT specification (section 7.2.5.1, compressed, 5836 bytes, checksum
E619D30Dh), taken from an exFAT image that has it (mkfs.exfat writes it).
python3 tools/exfat/mkupcase.py IMAGE > common/exfat/upcase.c"""
import struct
import sys

f = open(sys.argv[1], 'rb').read()
ss = 1 << f[108]
cs = ss << f[109]
heap = struct.unpack_from('<I', f, 88)[0] * ss
root = struct.unpack_from('<I', f, 96)[0]
table = None
for i in range(0, cs, 32):
    e = f[heap + (root - 2) * cs + i:][:32]
    if e[0] == 0x82:
        first, length = struct.unpack_from('<IQ', e, 20)
        table = f[heap + (first - 2) * cs:][:length]
s = 0
for b in table:
    s = ((s >> 1) | ((s & 1) << 31)) + b & 0xFFFFFFFF
if len(table) != 5836 or s != 0xE619D30D:
    sys.exit('not the recommended up-case table')
print('/* Generated by tools/exfat/mkupcase.py: the recommended up-case table of')
print('   the exFAT specification (7.2.5.1), compressed, checksum E619D30Dh. */')
print('#include "openaspi/exfat_format.h"')
print('const oa_u8 oa_exfmt_upcase[OA_EXFMT_UPCASE_LEN] = {')
for i in range(0, len(table), 16):
    print('    ' + ','.join('0x%02X' % b for b in table[i:i + 16]) + ',')
print('};')
