#!/usr/bin/env python3
"""Generates common/exfat/codepage.c: Unicode of the OEM characters 80h-FFh
and the DOS upper case of them for code pages 437 and 850.
python3 tools/exfat/mkcptab.py > common/exfat/codepage.c"""
import unicodedata

def upper(cp, c):
    u = bytes([c]).decode(cp)
    up = u.upper()
    if len(up) == 1:
        try:
            return up.encode(cp)[0]
        except UnicodeEncodeError:
            pass
    base = unicodedata.normalize('NFD', up)[0]
    if len(up) == 1 and 'A' <= base <= 'Z':
        return ord(base)
    return c

print('/* Generated by tools/exfat/mkcptab.py: Unicode and DOS upper case of the')
print('   OEM characters 80h-FFh of code pages 437 and 850. */')
print('#include "openaspi/exfat.h"')
for cp in (437, 850):
    name = 'cp%d' % cp
    print('const struct oa_exfat_cp oa_exfat_%s = { %d, {' % (name, cp))
    uni = [ord(bytes([c]).decode(name)) for c in range(128, 256)]
    for i in range(0, 128, 8):
        print('    ' + ','.join('0x%04X' % u for u in uni[i:i+8]) + ',')
    print('}, {')
    up = [upper(name, c) for c in range(128, 256)]
    for i in range(0, 128, 16):
        print('    ' + ','.join('0x%02X' % u for u in up[i:i+16]) + ',')
    print('} };')
