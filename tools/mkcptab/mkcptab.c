/* Host tool: writes common/cptab.c, the code pages 437 and 850 built into
   the DOS drivers and tools, from UNI_437.TAB and UNI_850.TAB of
   mars-unicode-tables through openfat's ofat_cp_load (make cptab).
   mkcptab UNITAB-directory > common/cptab.c */
#include <stdio.h>
#include <stdlib.h>
#include "openfat/codepage.h"

static void put(const char *dir, unsigned number)
{
    static ofat_u8 tab[8192];
    struct ofat_cp cp;
    char path[600];
    size_t len;
    unsigned i;
    FILE *f;
    sprintf(path, "%s/UNI_%03u.TAB", dir, number);
    if (!(f = fopen(path, "rb"))) { fprintf(stderr, "%s: cannot open\n", path); exit(1); }
    len = fread(tab, 1, sizeof(tab), f);
    fclose(f);
    if (ofat_cp_load(&cp, (ofat_u16)number, tab, (ofat_u32)len)) {
        fprintf(stderr, "%s: no single-byte code page\n", path);
        exit(1);
    }
    printf("const struct ofat_cp ofat_cp%u = { %u, {", number, number);
    for (i = 0; i < 128; ++i) printf("%s0x%04X%s", i % 8 ? "" : "\n    ", cp.uni[i], i < 127 ? "," : "");
    printf(" }, {");
    for (i = 0; i < 128; ++i) printf("%s0x%02X%s", i % 8 ? "" : "\n    ", cp.upper[i], i < 127 ? "," : "");
    printf(" } };\n");
}

int main(int argc, char **argv)
{
    if (argc != 2) { fprintf(stderr, "usage: mkcptab UNITAB-directory\n"); return 2; }
    printf("/* Generated by tools/mkcptab (make cptab) from UNI_437.TAB and UNI_850.TAB\n"
           "   of mars-unicode-tables: the Unicode and DOS upper case of the OEM\n"
           "   characters 80h-FFh, as openfat's ofat_cp_load fills them. */\n"
           "#include \"openaspi/cptab.h\"\n");
    put(argv[1], 437);
    put(argv[1], 850);
    return 0;
}
